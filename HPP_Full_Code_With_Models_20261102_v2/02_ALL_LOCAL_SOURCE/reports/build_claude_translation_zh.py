section('2.1', '设计①：一阶段层级估计', r'''
**估计对象。** Astra把目标定义为依赖模型的条件对比，因此它依赖于对 $m_k$ 的设定：

$$
\Delta_k(o,g;c,d,\delta)=m_k(d+\delta,o,g,c)-m_k(d,o,g,c)
$$

【拟议】主估计对象改用不依赖模型形式的**个人内线性投影斜率** $\beta_i$：给定背景c，个人i内部Y对D的最佳线性投影斜率。目标是 $E[\beta_i\mid O,G]$，以及 $\operatorname{Var}(\beta_i)$ 中O和G能够解释的份额。即使真实曲线非线性，$\beta_i$ 仍有明确含义：这个人在自己实际摄入范围内的平均斜率。非线性另用总体曲线描述。

**数据结构。** 日级记录中位数为每人9天；餐级约每人25餐（91,144／3,631）。个人斜率精度取决于个人内暴露方差与残差噪声，而非总人日数。

**一阶段与两阶段。** Astra反对“先逐人拟合斜率，再关联菌群”。这个反对只针对一种做法成立：把收缩后的BLUP斜率当作没有误差的结局，因为收缩程度依赖 $n_i$，会导致偏倚和衰减。

在与一阶段模型相同的严格外生性假设下，用未收缩的个人OLS斜率回归O和G，对跨层系数是无偏的：$\hat\beta_i$ 的估计误差均值为0，且独立于 $O_i,G_i$，所以第二阶段结局中的噪声损失的是精度，不是产生偏倚。精度权重 $1/(SE_i^2+\tau^2_{\mathrm{resid}})$ 中，$\tau^2_{\mathrm{resid}}$ 指O和G调整后的残余斜率方差，不是总 $\tau^2$；只要权重独立于斜率估计误差，权重只影响效率。当SE由合并的残差方差和个人设计（$n_i$、个人内 $\operatorname{Var}(x)$）构造时，该条件成立；在高斯误差下，即使个人方差不同，该条件也成立。每人残差自由度约7，应使用合并的 $\sigma^2$。

两阶段估计与一阶段混合模型（GLS）只在最简单的情形下相同：线性模型、在合并的个人内步骤中剔除合并估计的干扰协变量、方差分量正确、截距—斜率协方差得到处理（x按个人中心化后，这一点影响很小）。其他情况下效率较低，但仍具有一致性；参见Burke、Ensor与Riley，Statistics in Medicine 2017对两类方法何时不同的讨论。对于用岭回归学习评分，这些并非关键：交叉拟合评分不必无偏，因为真正接受检验的是留出数据中的校准斜率γ（2.3节）。学习评分可用两阶段，γ、方差分量与推断使用一阶段模型。“一阶段”是标准的跨层交互，不能本身当作方法优势。

**遗漏的竞争解释**——每项都可能表现得像“菌群标记反应”：

1. **习惯饮食的代理。** 本队列中G强烈反映习惯饮食：155种（Model 2）／146种（BMI调整Model 3）肠道物种在四种健康饮食评分中均显著且同向【核实表】。项目尚未分析O；HPP口腔NC2026报告颊拭子宏基因组与44项多系统代谢表型的关联，但其是否报告饮食关联仍【待核实】。因此，应预期两部位都可能代理习惯饮食。如果总体曲线是凸的，习惯NOVA4较高的人自然拥有更陡斜率，菌群可能只是 $\bar D_i$ 的代理。Astra把 $\bar D_i$ 放在h中，却没有 $x\times\bar D_i$；基线必须包括该项与总体非线性。
2. **血糖幅度或尺度。** 以mg/dL计，整体血糖波动更大的人对各种暴露都可能呈现较陡斜率。菌群可能标记“血糖幅度”这一宿主特质，而非饮食特异反应。评价回归的敏感性版本可以加入x×个人水平及x×个人幅度，但这些量的定义不能包含正在评价的斜率。个人水平（平均血糖）可以使用：个人中心化x后，均值与斜率估计正交，x×水平只是对截距—斜率协方差建模，而一阶段模型本来就直接估计 $\operatorname{cov}(a_i,u_i)$；Toumi与Salathé的截距条件化是先例。不能用个人全部日间／日内血糖SD定义幅度，因为 $\operatorname{Var}_t(Y_{it})=\beta_i^2\operatorname{Var}_t(x_{it})+\sigma_i^2$：这个修饰变量包含个人斜率的平方，x×幅度会吸收γ本想识别的部分异质性。在2.3节假设下，日级影响可忽略，但在碳水解释Net可见份额的餐级会有实质影响；对第二结局为日SD的C3还会构成循环。应改用斜率回归的个人内残差SD $\hat\sigma_i$，它在高斯误差下独立于斜率估计。两者均应标为“由结局派生的修饰变量”，并说明估计对象改为“超出本人血糖水平及噪声的异质性”；不放进主要γ检验。对幅度解释的主要防线应是第二个对比的特异性检验（2.2节）。
3. **宿主代谢状态。** 年龄、性别、BMI、吸烟、PPI，以及若存在的HbA1c、空腹血糖、内脏脂肪【待核实】。吸烟、口腔健康会强烈影响口腔群落；PPI与口腔菌进入肠道有关。Astra只写“年龄、BMI等”，应列出明确清单。
4. **日级混杂。** 高NOVA4日可能也是外食日、周末、睡眠或活动不同的日期，或记录不全的日期。个人固定效应不能处理这些；已记录的星期、传感器日序、记录能量与餐数、酒精等只能部分控制。若这种混杂结构因人而异并与菌群相关，就会表现为“菌群修饰斜率”。
5. **NOVA4是占比。** 提高其占比必然减少其他食物来源的占比。不说明替代对象，斜率含义就是模糊的。Astra在10月14日较早版本提过此问题，但新计划仍以NOVA4为入口。
6. **个人暴露测量可靠性。** 自由生活日志的真实摄入测量误差因人而异，包括少报、漏餐和份量取整。个人内斜率会按暴露可靠性 $\lambda_i=\operatorname{Var}(\text{真实}x)/\operatorname{Var}(\text{日志}x)$ 衰减，因此记录不完整者可能仅因测量原因而斜率更平。记录质量与教育、年龄、BMI及生活方式有关，这些也影响O和G，菌群就可能标记的是测量衰减。基线必须包含x×记录质量指标，如每日记录餐数、记录能量相对估计需要量、每天至少3餐的日期比例、CGM覆盖率；CLAN（2.3节）应展示评分是否将人群按这些指标分开。

**结局。** 日均值与日SD存在机械关联：SD随水平升高。给定Mean后，T096的W-SD交互失去支持【阶段记录】。应以日Mean加log(日SD)，或给定Mean的SD作为双结局，否则“共同方向”可能反映的是测量关系。

**对称。** 对称的块内标准化与正则化，不意味着两块使用相同惩罚。两块的维数、信号和测量质量不同。正确做法是相同程序、每块独立调惩罚，即多惩罚岭回归（van de Wiel等，JCGS2021）。同时承认测量不对称：颊拭子和粪便在采样时间差、测序深度和日内变化上不同。“O在G之外无增量”可能只因口腔测量更嘈杂，不能证明口腔生物信息为零。有重复样本时可估计评分可靠性并校正衰减。
''')

